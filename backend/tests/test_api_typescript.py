"""The dashboard's generated TypeScript types: what the generator writes, and that the committed
file matches the API's models (as tests/test_contract_schema.py does for the contract schema)."""

import pytest

from moonwalkers.api.app import create_app
from moonwalkers.api.typescript import (
    TS_PATH,
    UnsupportedSchemaError,
    declaration,
    render_typescript,
    ts_type,
)


def test_the_committed_types_match_the_api() -> None:
    expected = render_typescript(create_app(dashboard_dir=None).openapi())
    assert TS_PATH.read_text(encoding="utf-8") == expected, (
        "dashboard/src/api/types.gen.ts is out of date; regenerate it from backend/ with "
        "`uv run python -m moonwalkers.api.typescript`"
    )


@pytest.mark.parametrize(
    ("schema", "expected"),
    [
        ({"$ref": "#/components/schemas/Source"}, "Source"),
        ({"anyOf": [{"type": "string"}, {"type": "null"}]}, "string | null"),
        ({"anyOf": [{"type": "number"}, {"type": "integer"}]}, "number"),
        ({"type": "string", "enum": ["a", "it's"]}, "'a' | 'it\\'s'"),
        ({"const": "0.1.0", "type": "string"}, "'0.1.0'"),
        (
            {"type": "array", "prefixItems": [{"type": "number"}] * 3, "minItems": 3},
            "[number, number, number]",
        ),
        ({"type": "array", "items": {"$ref": "#/components/schemas/Fact"}}, "Fact[]"),
        (
            {"type": "array", "items": {"anyOf": [{"type": "string"}, {"type": "null"}]}},
            "(string | null)[]",
        ),
        ({"type": "object", "additionalProperties": True}, "Record<string, unknown>"),
        ({"type": "object", "additionalProperties": {"type": "integer"}}, "Record<string, number>"),
        ({"type": ["string", "null"]}, "string | null"),
        ({"title": "Anything"}, "unknown"),
        ({"type": "string", "format": "date-time", "description": "when"}, "string"),
    ],
)
def test_schemas_become_typescript_types(schema, expected) -> None:
    assert ts_type(schema) == expected


def test_objects_become_interfaces_with_optional_fields_and_comments() -> None:
    schema = {
        "type": "object",
        "description": "A thing. It has */ in its text.",
        "properties": {
            "id": {"type": "string", "description": "the\n  id"},
            "note": {"anyOf": [{"type": "string"}, {"type": "null"}]},
            "odd-name": {"type": "boolean"},
        },
        "required": ["id"],
        "additionalProperties": False,
    }
    assert declaration("Thing", schema) == (
        "/** A thing. It has * / in its text. */\n"
        "export interface Thing {\n"
        "  /** the id */\n"
        "  id: string\n"
        "  note?: string | null\n"
        '  "odd-name"?: boolean\n'
        "}"
    )


@pytest.mark.parametrize(
    "schema",
    [
        {"oneOf": [{"type": "string"}]},
        {"allOf": [{"$ref": "#/components/schemas/A"}]},
        {"type": "object", "patternProperties": {"^x": {"type": "string"}}},
        {"type": "string", "not": {"const": "x"}},
    ],
)
def test_json_schema_it_does_not_handle_stops_the_generator(schema) -> None:
    with pytest.raises(UnsupportedSchemaError):
        ts_type(schema)


def test_a_whole_document_is_sorted_and_headed() -> None:
    text = render_typescript(
        {"components": {"schemas": {"B": {"type": "string"}, "A-Output": {"type": "integer"}}}}
    )
    assert text.startswith("// Generated by `uv run python -m moonwalkers.api.typescript`")
    assert text.index("export type AOutput = number") < text.index("export type B = string")
    assert text.endswith("export type B = string\n")
