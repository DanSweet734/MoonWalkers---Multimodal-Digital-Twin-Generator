"""TypeScript types for the dashboard, generated from the API's OpenAPI schema (decision 0014).

``dashboard/src/api/types.gen.ts`` is never edited by hand: change the Pydantic models, then run
(from ``backend/``)::

    uv run python -m moonwalkers.api.typescript

``tests/test_api_typescript.py`` fails when the file no longer matches the models. The schema
includes the contract models the API returns (``PipelineResult``, ``TwinRecord``, ``Source``), so
the contract and the dashboard cannot drift apart.

Only the JSON Schema that Pydantic writes for our models is handled, and anything else stops the
generator rather than being guessed. A field the schema does not list as required gets ``?``,
even when the API always sends it (Pydantic does not list fields that have defaults).
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from .app import create_app

TS_PATH = Path(__file__).resolve().parents[4] / "dashboard" / "src" / "api" / "types.gen.ts"
HEADER = """\
// Generated by `uv run python -m moonwalkers.api.typescript` from the API's OpenAPI schema
// (decision 0014). Do not edit: change the Pydantic models in backend/ and regenerate.
// A field the schema does not list as required is optional (?), even if the API always sends it.
"""
# Keywords that only describe or constrain values, not their TypeScript type.
IGNORED = frozenset(
    {
        "title",
        "description",
        "default",
        "format",
        "minimum",
        "maximum",
        "minLength",
        "maxLength",
        "minItems",
        "maxItems",
        "pattern",
        "contentMediaType",
        "examples",
    }
)
SCALARS = {
    "string": "string",
    "integer": "number",
    "number": "number",
    "boolean": "boolean",
    "null": "null",
}
IDENTIFIER = re.compile(r"[A-Za-z_$][A-Za-z0-9_$]*")


class UnsupportedSchemaError(ValueError):
    """The schema uses JSON Schema the generator does not translate."""


def render_typescript(openapi: dict[str, Any]) -> str:
    """The ``types.gen.ts`` text for an OpenAPI document's component schemas."""
    schemas = openapi.get("components", {}).get("schemas", {})
    blocks = [declaration(type_name(name), schemas[name]) for name in sorted(schemas)]
    return HEADER + "".join(f"\n{block}\n" for block in blocks)


def declaration(name: str, schema: dict[str, Any]) -> str:
    doc = comment(schema.get("description"), "")
    if schema.get("type") == "object" and "properties" in schema:
        return f"{doc}export interface {name} {fields(schema, '  ')}"
    return f"{doc}export type {name} = {ts_type(schema)}"


def fields(schema: dict[str, Any], indent: str) -> str:
    """The ``{ ... }`` body of an object type, one property per line."""
    _check(schema, {"type", "properties", "required", "additionalProperties"})
    required = set(schema.get("required", []))
    lines = []
    for prop, sub in schema["properties"].items():
        key = prop if IDENTIFIER.fullmatch(prop) else json.dumps(prop)
        optional = "" if prop in required else "?"
        doc = comment(sub.get("description"), indent)
        lines.append(f"{doc}{indent}{key}{optional}: {ts_type(sub)}")
    closing = indent[:-2]
    return "{\n" + "\n".join(lines) + f"\n{closing}}}"


def ts_type(schema: dict[str, Any]) -> str:
    """The TypeScript type for one schema."""
    if "$ref" in schema:
        _check(schema, {"$ref"})
        return type_name(schema["$ref"].rsplit("/", 1)[-1])
    if "anyOf" in schema:
        _check(schema, {"anyOf"})
        return union(ts_type(s) for s in schema["anyOf"])
    if "const" in schema:
        _check(schema, {"const", "type"})
        return literal(schema["const"])
    if "enum" in schema:
        _check(schema, {"enum", "type"})
        return union(literal(v) for v in schema["enum"])
    kind = schema.get("type")
    if isinstance(kind, list):
        return union(ts_type({**schema, "type": k}) for k in kind)
    if kind == "array":
        _check(schema, {"type", "items", "prefixItems"})
        if "prefixItems" in schema:
            return "[" + ", ".join(ts_type(s) for s in schema["prefixItems"]) + "]"
        item = ts_type(schema.get("items", {}))
        return f"({item})[]" if "|" in item else f"{item}[]"
    if kind == "object":
        if "properties" in schema:
            return fields(schema, "    ")
        _check(schema, {"type", "additionalProperties"})
        extra = schema.get("additionalProperties", True)
        value = "unknown" if extra is True or extra == {} else ts_type(extra)
        return f"Record<string, {value}>"
    if kind in SCALARS:
        _check(schema, {"type"})
        return SCALARS[kind]
    if not set(schema) - IGNORED:
        return "unknown"  # an empty schema accepts anything
    raise UnsupportedSchemaError(f"no TypeScript type for schema {json.dumps(schema)}")


def type_name(name: str) -> str:
    """A TypeScript identifier for a schema name (FastAPI may write ``Model-Input``)."""
    cleaned = re.sub(r"[^A-Za-z0-9_]", "", name)
    if not IDENTIFIER.fullmatch(cleaned):
        raise UnsupportedSchemaError(f"schema name {name!r} is not a usable type name")
    return cleaned


def literal(value: Any) -> str:
    if isinstance(value, str):
        return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"
    if isinstance(value, bool) or value is None or isinstance(value, int | float):
        return json.dumps(value)
    raise UnsupportedSchemaError(f"no TypeScript literal for {value!r}")


def union(types: Any) -> str:
    unique = list(dict.fromkeys(types))
    return " | ".join(unique) if unique else "never"


def comment(text: str | None, indent: str) -> str:
    if not text:
        return ""
    one_line = " ".join(text.split()).replace("*/", "* /")
    return f"{indent}/** {one_line} */\n"


def _check(schema: dict[str, Any], handled: set[str]) -> None:
    unknown = set(schema) - handled - IGNORED
    if unknown:
        raise UnsupportedSchemaError(
            f"unsupported JSON Schema keyword(s) {sorted(unknown)} in {json.dumps(schema)}"
        )


def write_typescript(path: Path = TS_PATH) -> Path:
    """Write the types with LF line endings on every platform; returns the path written."""
    text = render_typescript(create_app(dashboard_dir=None).openapi())
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    return path


if __name__ == "__main__":
    print(f"wrote {write_typescript()}")
